/**
 * Тело статьи — список блоков, а не готовая разметка.
 *
 * Редактор на бэкенде отдаёт структуру, а не HTML: так текст статьи нельзя
 * подменить разметкой и не приходится доверять чужому HTML на клиенте.
 * Галерея — отдельный блок: в макете это карусель со стрелками и полосками
 * прогресса, обычной чередой картинок её не собрать.
 */
