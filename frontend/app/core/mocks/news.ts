/** Полный архив статей — источник для страницы `/news`. */
export const MOCK_NEWS_ALL: MockNews[] = SEEDS.map((seed, index) => ({
  slug: seed.slug,
  title: seed.title,
  excerpt: seed.excerpt,
  dateLabel: seed.dateLabel,
  id: index + 1,
  image: COVERS[index % COVERS.length],
}));

export type MockNewsArticle = MockNews & { blocks: NewsBlock[] };

/**
 * Статья со slug из адреса или `null`, если такой нет.
 *
 * У статей без собственного тела оно собирается из анонса и обложки: витрина
 * должна открываться по любой карточке. Когда подключится API, эта ветка
 * исчезнет — текст придёт вместе со статьёй.
 */
export function findNewsArticle(slug: string): MockNewsArticle | null {
  const index = SEEDS.findIndex((seed) => seed.slug === slug);
  if (index === -1) return null;

  const seed = SEEDS[index];
  const item = MOCK_NEWS_ALL[index];

  return {
    ...item,
    blocks: seed.blocks ?? [
      { kind: "paragraph", text: seed.excerpt },
      { kind: "image", image: item.image },
      {
        kind: "paragraph",
        text: "Подробности появятся здесь после подключения редакционного раздела: сейчас страница показывает анонс статьи и её обложку.",
      },
    ],
  };
}

/** Адреса всех статей — для `generateStaticParams` и карты сайта. */
